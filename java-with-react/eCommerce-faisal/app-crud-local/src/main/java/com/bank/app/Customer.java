package com.bank.app;

import jakarta.persistence.*;

/*
 * @Entity: this class maps to a database table (named "customer" by default).
 * Each field becomes a column and each object is one row.
 * Hibernate creates/updates the table at startup (spring.jpa.hibernate.ddl-auto=update).
 * Think of it as the model/schema in Prisma or TypeORM.
 */
@Entity
public class Customer {

    // @Id: this field is the primary key (unique, NOT NULL).
    // GenerationType.IDENTITY: Postgres assigns the id itself (auto-increment),
    // so never set it on create. It is null until the row is saved.
    // Long (not long) so it can be null before saving.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    public Long id;

    // Plain fields become columns. Hibernate converts camelCase to snake_case:
    // firstName -> first_name, lastName -> last_name, phoneNumber -> phone_number
    public String firstName;
    public String lastName;

    // unique = true: the DB rejects two customers with the same email.
    // Only affects the table schema. A duplicate throws DataIntegrityViolationException on save.
    // With ddl-auto=update it does NOT get added to a table that already exists
    // (add it manually with ALTER TABLE ... ADD CONSTRAINT ... UNIQUE).
    @Column(unique = true)
    public String email;
    public String phoneNumber;

    // No-argument constructor: REQUIRED by JPA/Hibernate.
    // Hibernate creates an empty Customer, then fills the fields when it reads rows from the DB.
    // Jackson (JSON) also uses it with the setters to turn a request body into a Customer.
    // If you add another constructor later, keep this one or the app breaks.
    public Customer(){

    }

    // Getters and setters: Jackson uses them to read/write JSON
    // (the setters fill the object from the request, the getters build the response).
    // Your service code also calls them, e.g. customerDetails.setId(customerId).
    // The fields are public, so they would work without these, but getters/setters
    // are the standard Java convention. They can be generated by the IDE or by Lombok (@Data).
    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getFirstName() {
        return firstName;
    }

    public void setFirstName(String firstName) {
        this.firstName = firstName;
    }

    public String getLastName() {
        return lastName;
    }

    public void setLastName(String lastName) {
        this.lastName = lastName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhoneNumber() {
        return phoneNumber;
    }

    public void setPhoneNumber(String phoneNumber) {
        this.phoneNumber = phoneNumber;
    }


}
